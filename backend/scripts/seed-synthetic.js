// Loads SYNTHETIC climate data so the app can be demonstrated without NASA data.
// The data are labelled synthetic everywhere and real NASA data always takes priority.
// Usage: npm run db:seed:synthetic [-- --district=rajshahi --start=2001 --end=2025]

import { parseArgs } from 'node:util';
import { config } from '../src/config/env.js';
import { createPrismaClient } from '../src/data/prisma.js';
import { storeRun } from '../src/data/climateStore.js';
import { generateSyntheticSeries, hashString } from '../src/integrations/fixture/synthetic.js';

const { values } = parseArgs({
  options: { district: { type: 'string' }, start: { type: 'string' }, end: { type: 'string' } },
});
const startYear = Number(values.start ?? 2001);
const endYear = Number(values.end ?? new Date().getUTCFullYear() - 1);

const prisma = createPrismaClient(config.databaseUrl);
try {
  const where = values.district ? { slug: { in: values.district.split(',') } } : {};
  const districts = await prisma.district.findMany({ where, orderBy: { slug: 'asc' } });
  if (districts.length === 0) {
    console.error('No districts found. Run `npm run db:seed` first.');
    process.exitCode = 1;
  }
  for (const d of districts) {
    const days = generateSyntheticSeries({ startYear, endYear, seed: hashString(d.slug) });
    await storeRun(prisma, {
      districtId: d.id,
      days,
      run: {
        source: 'SYNTHETIC',
        product: 'Deterministic synthetic fixture (no climatic meaning)',
        isSynthetic: true,
        endpointUrl: 'synthetic://deterministic-fixture',
        requestParams: { generator: 'mulberry32', seed: hashString(d.slug), startYear, endYear },
        startDate: `${startYear}-01-01`,
        endDate: `${endYear}-12-31`,
        notes: 'SYNTHETIC: generated by software for demonstration. Not a NASA observation.',
      },
    });
    console.log(`${d.slug}: stored ${days.length} synthetic days (${startYear}-${endYear}).`);
  }
} finally {
  await prisma.$disconnect();
}
