// Read-only data access for the API. Keeps every database query in one place so the science
// code never touches the database and tests can swap in a fake repository.

import { FieldDistrictError, FieldGeometryError, FieldSessionConflictError } from '../utils/fieldErrors.js';
import { boundedSet } from '../utils/boundedCache.js';
import { MAX_DISTRICT_DISTANCE_KM } from '../geo/climateGrid.js';
import { IMERG_PROVIDER, imergPixelList } from '../geo/imergGrid.js';

const NASA_NOTE =
  'NASA POWER meteorological data come on a grid of roughly 0.5 degrees (tens of km). Values describe the grid cell around the district point, not a single field.';
const IMERG_NOTE =
  'NASA GPM IMERG daily precipitation (Final Run) is satellite-based, on a 0.1 degree grid. Each value here is the mean of the 0.1 degree pixels whose centres lie inside one NASA POWER grid cell (about 0.5 x 0.625 degrees), not a single field. The Final Run is delayed by up to about 4 months.';
const SYNTHETIC_NOTE =
  'SYNTHETIC data generated by software. It is not a NASA observation and has no climatic meaning; it exists only so the app can be demonstrated without NASA data.';

function isoDate(d) {
  return d.toISOString().slice(0, 10);
}

function toDistrict(row) {
  return {
    id: row.id,
    slug: row.slug,
    nameEn: row.nameEn,
    nameBn: row.nameBn,
    division: row.division,
    latitude: row.latitude,
    longitude: row.longitude,
    coordNote: row.coordNote,
  };
}

function toProvenance(run) {
  return {
    runId: run.id,
    source: run.source,
    product: run.product,
    isSynthetic: run.isSynthetic,
    dataStatus: run.isSynthetic ? 'demo' : 'cached',
    retrievedAt: run.retrievedAt.toISOString(),
    startDate: isoDate(run.startDate),
    endDate: isoDate(run.endDate),
    endpointUrl: run.endpointUrl,
    requestParams: run.requestParams,
    fillValue: run.fillValue,
    units: run.units,
    rowCount: run.rowCount,
    missingCount: run.missingCount,
    notes: run.notes,
    resolutionNote: run.isSynthetic ? SYNTHETIC_NOTE : (run.source === 'NASA GPM IMERG' ? IMERG_NOTE : NASA_NOTE),
  };
}


// Prisma wraps raw-query database errors (code P2010), so the PostgreSQL code 23505 is not on `error.code`.
// Match only the one-field-per-session constraint, so other unique violations are not reported as a session conflict.
export function isSessionUniqueViolation(error) {
  if (!error) return false;
  const text = [error.message, error.meta?.message, error.meta?.driverAdapterError?.message, error.meta?.driverAdapterError?.cause?.message]
    .filter((v) => typeof v === 'string').join(' ');
  const cause = error.meta?.driverAdapterError?.cause;
  const isUnique = error.code === '23505' || error.meta?.code === '23505' || cause?.originalCode === '23505'
    || cause?.kind === 'UniqueConstraintViolation' || text.includes('23505');
  return isUnique && (text.includes('Field_sessionId_key') || JSON.stringify(cause ?? {}).includes('sessionId'));
}

const SERIES_CACHE_MAX = 16; // about 9,000 daily rows each

export function createRepository(prisma) {
  const seriesCache = new Map(); // runId -> series (runs never change once stored); bounded, see boundedSet

  const fieldFromRow = (row) => ({
    id: row.id,
    name: row.name,
    districtId: row.districtId,
    district: row.districtSlug
      ? { id: row.districtId, slug: row.districtSlug, nameEn: row.districtNameEn, nameBn: row.districtNameBn }
      : undefined,
    boundary: row.boundary ? JSON.parse(row.boundary) : null,
    areaHa: row.areaHa,
    soilType: row.soilType,
    soilPh: row.soilPh,
    organicMatterPct: row.organicMatterPct,
    salinityDsM: row.salinityDsM,
    irrigationSource: row.irrigationSource,
    createdAt: row.createdAt.toISOString(),
    updatedAt: row.updatedAt.toISOString(),
  });

  async function sharedGridCells() {
    const rows = await prisma.$queryRaw`
      WITH ranked AS (
        SELECT "id", "districtId",
               ROW_NUMBER() OVER (
                 PARTITION BY "districtId"
                 ORDER BY "isSynthetic" ASC, "retrievedAt" DESC
               ) AS position
        FROM "DatasetRun"
        WHERE "status" = 'SUCCESS'
      ),
      fingerprints AS (
        SELECT r."districtId",
               md5(string_agg(
                 concat_ws('|', d."date"::text, d."precipMm"::text, d."tMaxC"::text, d."tMinC"::text),
                 ',' ORDER BY d."date"
               )) AS fingerprint
        FROM ranked r
        JOIN "ClimateDaily" d ON d."runId" = r."id"
        WHERE r.position = 1
        GROUP BY r."districtId"
      )
      SELECT f."districtId", array_agg(other."slug" ORDER BY other."slug") AS "sharedWith"
      FROM fingerprints f
      JOIN fingerprints same ON same.fingerprint = f.fingerprint
        AND same."districtId" <> f."districtId"
      JOIN "District" other ON other."id" = same."districtId"
      GROUP BY f."districtId"
      HAVING COUNT(*) > 0
    `;
    return new Map(rows.map((row) => [row.districtId, row.sharedWith]));
  }

  async function getFieldWithClient(client, id, sessionId) {
    const rows = await client.$queryRaw`
      SELECT f."id", f."name", f."districtId", f."areaHa", f."soilType", f."soilPh",
             f."organicMatterPct", f."salinityDsM", f."irrigationSource",
             f."createdAt", f."updatedAt",
             d."slug" AS "districtSlug", d."nameEn" AS "districtNameEn", d."nameBn" AS "districtNameBn",
             ST_AsGeoJSON(f."boundary") AS "boundary"
      FROM "Field" f
      JOIN "District" d ON d."id" = f."districtId"
      WHERE f."id" = ${id}::uuid AND f."sessionId" = ${sessionId}
    `;
    return rows[0] ? fieldFromRow(rows[0]) : null;
  }

  async function validateBoundary(client, boundary) {
    const rows = await client.$queryRaw`
      WITH input AS (
        SELECT ST_Multi(ST_SetSRID(ST_GeomFromGeoJSON(${JSON.stringify(boundary)}), 4326)) AS geometry
      )
      SELECT ST_IsValid(geometry) AS valid,
             ST_IsEmpty(geometry) AS empty,
             ST_Area(geometry::geography) AS area,
             ST_GeometryType(geometry) AS geometry_type
      FROM input
    `;
    const result = rows[0];
    if (!result || result.empty || result.geometry_type !== 'ST_MultiPolygon' || !result.valid || !(Number(result.area) > 0)) {
      throw new FieldGeometryError('Boundary must be a non-empty, valid polygon with a positive area.');
    }
  }

  // Loads (and caches) the daily rows of one stored run. Runs never change once stored.
  async function seriesForRun(run) {
    let series = seriesCache.get(run.id);
    if (!series) {
      const rows = await prisma.climateDaily.findMany({
        where: { runId: run.id },
        orderBy: { date: 'asc' },
        select: { date: true, precipMm: true, tMaxC: true, tMinC: true, measurements: true },
      });
      series = rows.map((r) => ({
        date: isoDate(r.date),
        precipMm: r.precipMm,
        tMaxC: r.tMaxC,
        tMinC: r.tMinC,
        measurements: r.measurements,
      }));
      boundedSet(seriesCache, run.id, series, SERIES_CACHE_MAX);
    }
    return series;
  }

  // Data-entry guard: a boundary far from its district's reference point is filed under the wrong district.
  async function assertNearDistrict(client, district, boundaryJson) {
    const maxMeters = MAX_DISTRICT_DISTANCE_KM * 1000;
    const rows = await client.$queryRaw`
      SELECT ST_DWithin(
        ST_Multi(ST_SetSRID(ST_GeomFromGeoJSON(${boundaryJson}), 4326))::geography,
        ST_SetSRID(ST_MakePoint(${district.longitude}, ${district.latitude}), 4326)::geography,
        ${maxMeters}
      ) AS near
    `;
    if (!rows[0]?.near) {
      throw new FieldGeometryError(`Boundary is more than ${MAX_DISTRICT_DISTANCE_KM} km from the reference point of the selected district. Check the district.`);
    }
  }

  async function assertStoredFieldNearDistrict(client, fieldId, district) {
    const maxMeters = MAX_DISTRICT_DISTANCE_KM * 1000;
    const rows = await client.$queryRaw`
      SELECT ST_DWithin(
        f."boundary"::geography,
        ST_SetSRID(ST_MakePoint(${district.longitude}, ${district.latitude}), 4326)::geography,
        ${maxMeters}
      ) AS near
      FROM "Field" f WHERE f."id" = ${fieldId}::uuid AND f."boundary" IS NOT NULL
    `;
    if (rows[0] && !rows[0].near) {
      throw new FieldGeometryError(`The field is more than ${MAX_DISTRICT_DISTANCE_KM} km from the reference point of the selected district. Check the district.`);
    }
  }

  return {
    async ping() {
      await prisma.$queryRaw`SELECT 1`;
      return true;
    },

    async listDistricts() {
      const [districts, runs, sharing] = await Promise.all([
        prisma.district.findMany({ orderBy: { nameEn: 'asc' } }),
        prisma.datasetRun.findMany({
          where: { status: 'SUCCESS' },
          select: { districtId: true, isSynthetic: true, retrievedAt: true, endDate: true, rowCount: true, missingCount: true },
          orderBy: [{ isSynthetic: 'asc' }, { retrievedAt: 'desc' }],
        }),
        sharedGridCells(),
      ]);
      const runStatus = new Map();
      for (const run of runs) {
        const status = runStatus.get(run.districtId);
        if (!status) {
          runStatus.set(run.districtId, {
            climateData: run.isSynthetic ? 'synthetic' : 'nasa',
            dataStatus: run.isSynthetic ? 'demo' : 'cached',
            latestObservationDate: isoDate(run.endDate),
            lastRetrievedAt: run.retrievedAt.toISOString(),
            rowCount: run.rowCount,
            missingCount: run.missingCount,
          });
        }
      }
      return districts.map((d) => {
        const status = runStatus.get(d.id);
        return {
          ...toDistrict(d),
          climateData: status?.climateData ?? 'none',
          dataStatus: status?.dataStatus ?? 'unavailable',
          latestObservationDate: status?.latestObservationDate ?? null,
          lastRetrievedAt: status?.lastRetrievedAt ?? null,
          rowCount: status?.rowCount ?? 0,
          missingCount: status?.missingCount ?? 0,
          sharedGridCellWith: sharing.get(d.id) ?? [],
        };
      });
    },

    async getDistrictBySlug(slug) {
      const row = await prisma.district.findUnique({ where: { slug } });
      if (!row) return null;
      const sharing = await sharedGridCells();
      return { ...toDistrict(row), sharedGridCellWith: sharing.get(row.id) ?? [] };
    },

    async listCrops() {
      return prisma.crop.findMany({ orderBy: { slug: 'asc' } });
    },

    async createField(input, sessionId) {
      if (!sessionId) throw new Error('Anonymous session is required to create a field.');
      return prisma.$transaction(async (tx) => {
        const district = await tx.district.findUnique({ where: { id: input.districtId }, select: { id: true, latitude: true, longitude: true } });
        if (!district) throw new FieldDistrictError(input.districtId);
        await validateBoundary(tx, input.boundary);
        await assertNearDistrict(tx, district, JSON.stringify(input.boundary));
        let ids;
        try {
          ids = await tx.$queryRaw`
          WITH input AS (
            SELECT ST_Multi(ST_SetSRID(ST_GeomFromGeoJSON(${JSON.stringify(input.boundary)}), 4326)) AS geometry
          )
          INSERT INTO "Field" (
            "id", "sessionId", "name", "districtId", "boundary", "areaHa", "soilType", "soilPh",
            "organicMatterPct", "salinityDsM", "irrigationSource", "updatedAt"
          )
          SELECT ${crypto.randomUUID()}::uuid, ${sessionId}, ${input.name}, ${input.districtId}, geometry,
                 ST_Area(geometry::geography) / 10000, ${input.soilType ?? null}, ${input.soilPh ?? null},
                 ${input.organicMatterPct ?? null}, ${input.salinityDsM ?? null}, ${input.irrigationSource ?? null},
                 CURRENT_TIMESTAMP
          FROM input
          RETURNING "id"
          `;
        } catch (error) {
          if (isSessionUniqueViolation(error)) throw new FieldSessionConflictError();
          throw error;
        }
        return getFieldWithClient(tx, ids[0].id, sessionId);
      });
    },

    async listFields(sessionId) {
      const rows = await prisma.$queryRaw`
        SELECT f."id", f."name", f."districtId", f."areaHa", f."soilType", f."soilPh",
               f."organicMatterPct", f."salinityDsM", f."irrigationSource",
               f."createdAt", f."updatedAt",
               d."slug" AS "districtSlug", d."nameEn" AS "districtNameEn", d."nameBn" AS "districtNameBn",
               ST_AsGeoJSON(f."boundary") AS "boundary"
        FROM "Field" f
        JOIN "District" d ON d."id" = f."districtId"
        WHERE f."sessionId" = ${sessionId}
        ORDER BY f."createdAt" DESC, f."id" ASC
      `;
      return rows.map(fieldFromRow);
    },

    getField: (id, sessionId) => getFieldWithClient(prisma, id, sessionId),

    async updateField(id, input, sessionId) {
      return prisma.$transaction(async (tx) => {
        const existing = await tx.field.findFirst({ where: { id, sessionId }, select: { id: true, districtId: true } });
        if (!existing) return null;
        let district = null;
        if (input.districtId !== undefined) {
          district = await tx.district.findUnique({ where: { id: input.districtId }, select: { id: true, latitude: true, longitude: true } });
          if (!district) throw new FieldDistrictError(input.districtId);
        }
        if (input.boundary !== undefined) {
          await validateBoundary(tx, input.boundary);
          const target = district ?? await tx.district.findUnique({ where: { id: existing.districtId }, select: { id: true, latitude: true, longitude: true } });
          await assertNearDistrict(tx, target, JSON.stringify(input.boundary));
          await tx.$executeRaw`
            UPDATE "Field"
            SET "boundary" = ST_Multi(ST_SetSRID(ST_GeomFromGeoJSON(${JSON.stringify(input.boundary)}), 4326)),
                "areaHa" = ST_Area(ST_Multi(ST_SetSRID(ST_GeomFromGeoJSON(${JSON.stringify(input.boundary)}), 4326))::geography) / 10000,
                "updatedAt" = CURRENT_TIMESTAMP
            WHERE "id" = ${id}::uuid AND "sessionId" = ${sessionId}
          `;
        }
        if (district && input.boundary === undefined) await assertStoredFieldNearDistrict(tx, id, district);
        const data = {};
        for (const key of ['name', 'districtId', 'soilType', 'soilPh', 'organicMatterPct', 'salinityDsM', 'irrigationSource']) {
          if (input[key] !== undefined) data[key] = input[key];
        }
        if (Object.keys(data).length) await tx.field.update({ where: { id }, data });
        return getFieldWithClient(tx, id, sessionId);
      });
    },

    async deleteField(id, sessionId) {
      const result = await prisma.field.deleteMany({ where: { id, sessionId } });
      return result.count > 0;
    },

    // Daily climate for one district, from ONE source. Real data wins over synthetic demo data;
    // otherwise the newest successful run. A run from another real source (for example a future GPM IMERG
    // run) is never returned here: sources are not interchangeable and must not be mixed.
    async getClimate(districtId, { source = 'NASA POWER' } = {}) {
      const run = await prisma.datasetRun.findFirst({
        where: { districtId, status: 'SUCCESS', OR: [{ source }, { isSynthetic: true }] },
        orderBy: [{ isSynthetic: 'asc' }, { retrievedAt: 'desc' }],
      });
      if (!run) return null;
      return { provenance: toProvenance(run), series: await seriesForRun(run) };
    },

    // Daily climate for one provider grid cell: the newest successful REAL run recorded against that cell.
    // Synthetic runs are never returned. Returns null when the cell has no stored run.
    async getClimateByCell(cell, { source = 'NASA POWER' } = {}) {
      const stored = await prisma.climateGridCell.findUnique({
        where: { provider_cellKey: { provider: cell.provider, cellKey: cell.cellKey } },
        select: { id: true },
      });
      if (!stored) return null;
      const run = await prisma.datasetRun.findFirst({
        where: { gridCellId: stored.id, status: 'SUCCESS', isSynthetic: false, source },
        orderBy: [{ retrievedAt: 'desc' }, { id: 'desc' }],
      });
      if (!run) return null;
      return { provenance: toProvenance(run), series: await seriesForRun(run) };
    },

    // Native GPM IMERG pixels (0.1 degree) of a pixel block: for every pixel of the block that has a stored real run, its
    // daily values with the valid half-hourly count and the file version. Nothing is aggregated here. Returns null when no
    // pixel of the block has data. Reads the one newest successful run per pixel.
    async getImergBlock(block) {
      const keys = imergPixelList(block).map((p) => p.cellKey);
      const runs = await prisma.datasetRun.findMany({
        where: { status: 'SUCCESS', isSynthetic: false, source: IMERG_PROVIDER, gridCell: { provider: IMERG_PROVIDER, cellKey: { in: keys } } },
        orderBy: [{ retrievedAt: 'desc' }, { id: 'desc' }],
        include: { gridCell: { select: { cellKey: true } } },
      });
      const newest = new Map();
      for (const r of runs) if (!newest.has(r.gridCell.cellKey)) newest.set(r.gridCell.cellKey, r);
      if (newest.size === 0) return null;
      const runIds = [...newest.values()].map((r) => r.id);
      const rows = await prisma.$queryRaw`
        SELECT c."cellKey" AS "cellKey", d."date" AS "date", d."precipMm" AS "precipMm",
               (d."measurements"->>'precipitationCnt')::int AS "precipitationCnt",
               d."measurements"->>'fileVersion' AS "fileVersion"
        FROM "ClimateDaily" d
        JOIN "DatasetRun" r ON r."id" = d."runId"
        JOIN "ClimateGridCell" c ON c."id" = r."gridCellId"
        WHERE d."runId" = ANY(${runIds}::int[])
        ORDER BY d."date", c."cellKey"`;
      return {
        pixelsExpected: keys.length,
        runs: [...newest.entries()].map(([cellKey, r]) => ({
          cellKey, runId: r.id, retrievedAt: r.retrievedAt.toISOString(), startDate: isoDate(r.startDate), endDate: isoDate(r.endDate),
          rowCount: r.rowCount, missingCount: r.missingCount, product: r.product, requestParams: r.requestParams, units: r.units,
        })),
        rows: rows.map((x) => ({ cellKey: x.cellKey, date: isoDate(x.date), precipMm: x.precipMm, precipitationCnt: x.precipitationCnt, fileVersion: x.fileVersion })),
      };
    },

    // Where a registered field is, as PostGIS sees it. The representative point is ST_PointOnSurface:
    // unlike the centroid it is guaranteed to lie ON the polygon, even for concave or multi-part shapes.
    async getFieldGeoContext(id, sessionId) {
      const rows = await prisma.$queryRaw`
        SELECT f."id", f."name", f."areaHa", f."districtId",
               d."slug" AS "districtSlug", d."nameEn" AS "districtNameEn", d."nameBn" AS "districtNameBn",
               ST_Y(ST_PointOnSurface(f."boundary")) AS "lat",
               ST_X(ST_PointOnSurface(f."boundary")) AS "lon",
               ST_XMin(f."boundary") AS "minLon", ST_XMax(f."boundary") AS "maxLon",
               ST_YMin(f."boundary") AS "minLat", ST_YMax(f."boundary") AS "maxLat",
               (
                 SELECT COUNT(*) > 1
                 FROM generate_series(
                   FLOOR(ST_YMin(f."boundary") / 0.5 - 0.5)::integer,
                   CEIL(ST_YMax(f."boundary") / 0.5 + 0.5)::integer
                 ) AS lat(lat_idx)
                 CROSS JOIN generate_series(
                   FLOOR((ST_XMin(f."boundary") + 180) / 0.625 - 0.5)::integer,
                   CEIL((ST_XMax(f."boundary") + 180) / 0.625 + 0.5)::integer
                 ) AS lon(lon_idx)
                 WHERE ST_Area(ST_Intersection(
                   f."boundary",
                   ST_MakeEnvelope(
                     -180 + lon_idx * 0.625 - 0.3125,
                     lat_idx * 0.5 - 0.25,
                     -180 + lon_idx * 0.625 + 0.3125,
                     lat_idx * 0.5 + 0.25,
                     4326
                   )
                 )) > 0
               ) AS "spansMultipleCells"
        FROM "Field" f
        JOIN "District" d ON d."id" = f."districtId"
        WHERE f."id" = ${id}::uuid AND f."sessionId" = ${sessionId} AND f."boundary" IS NOT NULL
      `;
      const r = rows[0];
      if (!r) return null;
      return {
        id: r.id,
        name: r.name,
        areaHa: r.areaHa,
        district: { id: r.districtId, slug: r.districtSlug, nameEn: r.districtNameEn, nameBn: r.districtNameBn },
        point: { lat: Number(r.lat), lon: Number(r.lon) },
        bbox: { minLon: Number(r.minLon), maxLon: Number(r.maxLon), minLat: Number(r.minLat), maxLat: Number(r.maxLat) },
        spansMultipleCells: r.spansMultipleCells,
      };
    },

    // Most recent failed ingestion attempts, shown to developers via /api/health/data.
    async recentFailedRuns(limit = 10) {
      const runs = await prisma.datasetRun.findMany({
        where: { status: 'FAILED' },
        orderBy: { retrievedAt: 'desc' },
        take: limit,
        include: { district: { select: { slug: true } }, gridCell: { select: { cellKey: true } } },
      });
      return runs.map((r) => ({
        district: r.district?.slug ?? null,
        cellKey: r.gridCell?.cellKey ?? null,
        source: r.source,
        retrievedAt: r.retrievedAt.toISOString(),
        errorMessage: r.errorMessage,
      }));
    },
  };
}
