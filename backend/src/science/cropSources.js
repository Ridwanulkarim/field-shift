// Merges human-verified, cited trait values (from the generated overlay file) into the crop table. Pure functions.
//
// Every trait of every crop gets a source record:
//   { basis: 'UNVERIFIED_GENERAL_KNOWLEDGE' }                      the original typed-in value, unchanged
//   { basis: 'VERIFIED', citation: { title, organisation, ... } }  a value a named reviewer checked against a cited source
// crop.basis (kept for older consumers) is 'UNVERIFIED_GENERAL_KNOWLEDGE', 'PARTIALLY_VERIFIED' or 'VERIFIED'.
// The overlay is re-checked on load with the same range rules as the sheet checker, so a hand-edited overlay cannot
// smuggle in an impossible value or a value without a citation.

import { TRAITS, checkTraitValue } from './cropSheet.js';

export const UNVERIFIED = 'UNVERIFIED_GENERAL_KNOWLEDGE';
export const VERIFIED = 'VERIFIED';
export const PARTIALLY_VERIFIED = 'PARTIALLY_VERIFIED';
const CITATION_REQUIRED = ['title', 'organisation', 'yearOrEdition', 'pageOrTable', 'appliesTo', 'reviewer', 'reviewDate'];

export function applyCropSources(baseCrops, overlay) {
  const approved = overlay?.approved ?? [];
  const bySlug = new Map(baseCrops.map((c) => [c.slug, { ...c }]));
  const sources = new Map(baseCrops.map((c) => [c.slug, Object.fromEntries(Object.keys(TRAITS).map((t) => [t, { basis: UNVERIFIED }]))]));
  const seen = new Set();
  for (const a of approved) {
    const crop = bySlug.get(a.slug);
    if (!crop) throw new Error(`cropSources: unknown crop "${a.slug}".`);
    if (!(a.trait in TRAITS)) throw new Error(`cropSources: unknown trait "${a.trait}" for ${a.slug}.`);
    const key = `${a.slug}/${a.trait}`;
    if (seen.has(key)) throw new Error(`cropSources: duplicate entry ${key}.`);
    seen.add(key);
    const checked = checkTraitValue(a.trait, String(a.value));
    if (!checked.ok) throw new Error(`cropSources: ${key}: ${checked.message}`);
    const missing = CITATION_REQUIRED.filter((f) => !a.citation || a.citation[f] === undefined || a.citation[f] === null || String(a.citation[f]).trim() === '');
    if (missing.length) throw new Error(`cropSources: ${key} has no ${missing.join(', ')} in its citation.`);
    crop[a.trait] = checked.value;
    sources.get(a.slug)[a.trait] = { basis: VERIFIED, citation: a.citation };
  }
  return [...bySlug.values()].map((crop) => {
    const traitSources = sources.get(crop.slug);
    const n = Object.values(traitSources).filter((s) => s.basis === VERIFIED).length;
    const basis = n === 0 ? UNVERIFIED : n === Object.keys(TRAITS).length ? VERIFIED : PARTIALLY_VERIFIED;
    return { ...crop, basis, traitSources };
  });
}

// Converts approved rows (from validateCropSheet) into the overlay file's content. Contains no timestamp, so the output is
// reproducible: the same sheet always produces the same file.
export function buildOverlay(approvedRows, { sheetName }) {
  const approved = [...approvedRows]
    .sort((a, b) => a.slug.localeCompare(b.slug) || a.trait.localeCompare(b.trait))
    .map(({ slug, trait, value, citation }) => ({ slug, trait, value, citation }));
  return { _comment: 'GENERATED by npm run build:crop-sources from the reviewed crop sheet. Do not edit by hand.', generatedFrom: sheetName, approved };
}
