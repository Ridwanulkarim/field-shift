export function makeT(lang) {
  const table = STRINGS[lang] ?? STRINGS.en;
  return (key) => table[key] ?? STRINGS.en[key] ?? key;
}

const MONTHS = ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec'];
const MONTHS_BN = ['জানু', 'ফেব্রু', 'মার্চ', 'এপ্রিল', 'মে', 'জুন', 'জুলাই', 'আগস্ট', 'সেপ্টে', 'অক্টো', 'নভে', 'ডিসে'];

export function monthRange(months, lang) {
  if (!months?.length) return '';
  const names = lang === 'bn' ? MONTHS_BN : MONTHS;
  const first = names[months[0] - 1];
  const last = names[months[months.length - 1] - 1];
  return first === last ? first : `${first}–${last}`;
}
